// Pure core of the AI attribution scrub and check (no I/O, no network).
// The synced workflows run inside actions/github-script in other repos, where this file does not exist, so each block is
// copied verbatim between its BEGIN/END markers into the templates that use it:
//   aiAgents       -> templates/ai-attribution-scrub.yml and templates/ai-attribution-check.yml (the one list of AI tools)
//   scrubBody      -> templates/ai-attribution-scrub.yml
//   commitProblems -> templates/ai-attribution-check.yml
// test/ai-attribution-scrub.test.mjs and test/ai-attribution-check.test.mjs fail if a copy drifts from this file.
// Keep the blocks free of `getOctokit` declarations (github-script v9) and of anything but plain JavaScript.

// BEGIN aiAgents
export const AI_AGENTS = {
  // One entry per AI tool. `names` match a whole author or committer name or login (case-insensitive, a trailing [bot] is
  // ignored); `emails` match a whole email; `emailSuffixes` match the end of an email; `words` match inside a Co-Authored-By
  // trailer; `footers` are the tool names in a trailing "Generated by/with <tool>" line.
  agents: [
    { label: "Claude", names: ["claude"], emails: ["noreply@anthropic.com"], emailSuffixes: [], words: ["claude", "anthropic"], footers: ["Claude Code"] },
    { label: "Codex", names: ["codex", "chatgpt-codex-connector"], emails: ["codex@openai.com"], emailSuffixes: ["@openai.com", "+chatgpt-codex-connector[bot]@users.noreply.github.com"], words: ["codex"], footers: ["Codex", "OpenAI Codex"] },
    { label: "Cursor Agent", names: ["cursor agent", "cursoragent"], emails: ["cursoragent@cursor.com"], emailSuffixes: [], words: ["cursor agent"], footers: ["Cursor", "Cursor Agent"] },
    { label: "Copilot", names: ["copilot", "copilot-swe-agent"], emails: [], emailSuffixes: ["+copilot@users.noreply.github.com", "+copilot-swe-agent[bot]@users.noreply.github.com"], words: ["copilot"], footers: ["GitHub Copilot", "Copilot"] },
    { label: "Jules", names: ["jules", "google-labs-jules"], emails: [], emailSuffixes: ["+google-labs-jules[bot]@users.noreply.github.com"], words: ["google-labs-jules"], footers: ["Jules", "Google Jules"] },
    { label: "Gemini", names: ["gemini-code-assist"], emails: [], emailSuffixes: ["+gemini-code-assist[bot]@users.noreply.github.com"], words: ["gemini-code-assist"], footers: [] },
  ],
  // Trailer keys that mark a commit as made in an AI session.
  sessionTrailers: ["claude-session"],
  // Never AI authorship: Dependabot and GitHub Actions commits.
  ignore: { names: ["dependabot", "github-actions"], emailSuffixes: ["+dependabot[bot]@users.noreply.github.com", "+github-actions[bot]@users.noreply.github.com"] },
};

export function agentOf(who) {
  // `who` is { name, email } or { login }: returns the label of the AI tool it identifies, or "".
  const norm = (v) => String(v || "").trim().toLowerCase().replace(/\[bot\]$/, "");
  const email = String(who.email || "").trim().toLowerCase();
  for (const a of AI_AGENTS.agents) {
    if (who.name && a.names.includes(norm(who.name))) return a.label;
    if (who.login && a.names.includes(norm(who.login))) return a.label;
    if (email && (a.emails.includes(email) || a.emailSuffixes.some((x) => email.endsWith(x)))) return a.label;
  }
  return "";
}

export function agentInTrailer(value) {
  // `value` is the text after "Co-Authored-By:": returns the label of the AI tool it names, or "".
  const text = String(value || "").toLowerCase();
  const name = text.replace(/<[^>]*>/, "").trim();
  const email = (text.match(/<([^>]*)>/) || [])[1] || "";
  const who = agentOf({ name, email });
  if (who) return who;
  for (const a of AI_AGENTS.agents) {
    for (const w of a.words) {
      if (new RegExp("(?<![\\w-])" + w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "(?![\\w-])").test(text)) return a.label;
    }
  }
  return "";
}
// END aiAgents

// BEGIN scrubBody
export function scrubBody(body) {
  // Returns the body without a trailing AI footer, or the same string when there is nothing to remove.
  // Only the end of the body is ever cut: everything before the cut is returned byte for byte, line endings included.
  if (typeof body !== "string" || body === "") return body;
  const esc = (v) => v.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const tools = AI_AGENTS.agents.flatMap((a) => a.footers).sort((x, y) => y.length - x.length).map(esc).join("|");
  const generated = new RegExp("^\\s*[*_]*(?:\\u{1F916}\\uFE0F?\\s*)?Generated (?:by|with) (?:\\[(?:" + tools + ")\\]\\([^)\\s]*\\)|(?:" + tools + "))[*_]*\\.?\\s*$", "iu");
  const coAuthor = (t) => /^\s*co-authored-by[ \t]*:/i.test(t) && agentInTrailer(t.replace(/^[^:]*:/, "")) !== "";
  const session = /^\s*(?:claude-session:\s*)?(?:<|\[[^\]]*\]\()?https?:\/\/claude\.(?:ai|com)\/code\/session_[A-Za-z0-9_-]+(?:[?#][^\s)>]*)?[)>]?\s*$/i;
  const separator = /^\s*-{3,}\s*$/;
  const lines = [];
  for (let start = 0; ; ) {
    let end = start;
    while (end < body.length && body[end] !== "\n" && body[end] !== "\r") end++;
    lines.push({ text: body.slice(start, end), end });
    if (end >= body.length) break;
    start = end + (body[end] === "\r" && body[end + 1] === "\n" ? 2 : 1);
  }
  let i = lines.length - 1;
  let removed = false;
  for (; i >= 0; i--) {
    const t = lines[i].text;
    if (t.trim() === "") continue;
    if (generated.test(t) || coAuthor(t) || session.test(t)) { removed = true; continue; }
    if (removed && separator.test(t)) continue;
    break;
  }
  if (!removed) return body;
  return i < 0 ? "" : body.slice(0, lines[i].end);
}
// END scrubBody

// BEGIN commitProblems
export function commitProblems(c) {
  // `c` is one commit as returned by GET /repos/{owner}/{repo}/pulls/{number}/commits.
  // Returns the reasons the commit carries AI authorship (an empty list when it is fine).
  const git = c.commit || {};
  const author = { name: git.author && git.author.name, email: git.author && git.author.email };
  const committer = { name: git.committer && git.committer.name, email: git.committer && git.committer.email };
  const login = (c.author && c.author.login) || "";
  const norm = (v) => String(v || "").trim().toLowerCase().replace(/\[bot\]$/, "");
  const email = (v) => String(v || "").trim().toLowerCase();
  // Dependabot and GitHub Actions commits are ignored.
  const ign = AI_AGENTS.ignore;
  if (ign.names.includes(norm(login)) || ign.names.includes(norm(author.name)) || ign.emailSuffixes.some((x) => email(author.email).endsWith(x))) return [];
  // So are merge commits made by GitHub (the "Update branch" button, merge buttons): several parents, committed by GitHub.
  const merge = (c.parents || []).length > 1;
  if (merge && (email(committer.email) === "noreply@github.com" || norm(c.committer && c.committer.login) === "web-flow")) return [];
  const problems = [];
  const who = (role, p, extra) => {
    const byEmail = agentOf({ email: p.email });
    if (byEmail) problems.push(`${role} email is ${email(p.email)} (${byEmail})`);
    const byName = agentOf({ name: p.name, login: extra });
    const shown = String(p.name || extra || "").trim();
    if (byName) problems.push(`${role} name is "${shown}"` + (norm(shown) === byName.toLowerCase() ? "" : ` (${byName})`));
  };
  who("author", author, login);
  who("committer", committer, c.committer && c.committer.login);
  // Only the final trailer block counts, as git interpret-trailers reads it: the last paragraph, after a title paragraph,
  // where every line is a "Key: value" trailer (or an indented continuation of one). A line quoted in prose is not a trailer.
  const lines = String(git.message || "").split(/\r?\n/);
  while (lines.length && lines[lines.length - 1].trim() === "") lines.pop();
  let start = lines.length;
  while (start > 0 && lines[start - 1].trim() !== "") start--;
  const block = lines.slice(start);
  const trailers = [];
  let valid = start > 0 && lines.slice(0, start).some((l) => l.trim() !== "");
  for (const line of block) {
    if (/^[A-Za-z0-9-]+[ \t]*:/.test(line)) trailers.push(line);
    else if (/^[ \t]+\S/.test(line) && trailers.length > 0) trailers[trailers.length - 1] += " " + line.trim();
    else valid = false;
  }
  if (valid) {
    const named = new Set();
    for (const t of trailers) {
      if (/^co-authored-by[ \t]*:/i.test(t)) {
        const label = agentInTrailer(t.replace(/^[^:]*:/, ""));
        if (label) named.add(label);
      }
    }
    for (const label of named) problems.push(`message has a Co-Authored-By trailer naming ${label}`);
    if (trailers.some((t) => AI_AGENTS.sessionTrailers.includes(t.split(":")[0].trim().toLowerCase()))) problems.push("message has a Claude-Session trailer");
  }
  return problems;
}
// END commitProblems
