test("manifest: installed as .github/workflows/ai-attribution-scrub.yml, a replace file with repo-owned refs", () => {
  const f = MANIFEST.files.find((x) => x.id === "ai-attribution-scrub");
  assert.deepEqual(f, { id: "ai-attribution-scrub", src: SRC, dest: DEST, mode: "replace", refs: "repo" });
});

test("workflow: every action is pinned by a full commit SHA with a version comment", () => {
  const refs = usesRefs(TEMPLATE);
  assert.deepEqual(refs.map((u) => u.action), ["actions/github-script"]);
  for (const u of refs) {
    assert.ok(isSha(u.ref), `${u.action}@${u.ref} is a full SHA`);
    assert.match(u.comment, /^ # v\d+\.\d+\.\d+$/);
  }
  assert.equal(TEMPLATE.split("\n").filter((l) => /^\s*(-\s+)?uses:/.test(l)).length, refs.length, "every uses: line is a pinned third-party ref");
});

test("workflow: least privilege, no checkout, no privileged trigger, no secrets", () => {
  assert.match(TEMPLATE, /^permissions:\n {2}contents: read\n(?!\s+\w)/m, "workflow default is contents: read only");
  assert.match(TEMPLATE, /^ {2}scrub:\n {4}name: scrub\n {4}runs-on: ubuntu-latest\n {4}permissions:\n {6}contents: read\n {6}issues: write\n {6}pull-requests: write\n {4}steps:\n/m, "job scrub: exactly contents read, issues write, pull-requests write");
  const code = TEMPLATE.replace(/^\s*#.*$/gm, "");
  assert.ok(!/pull_request_target|workflow_run|id-token|secrets\.|actions\/checkout|persist-credentials/.test(code));
  assert.equal([...code.matchAll(/:\s*write\b/g)].length, 2, "only issues and pull-requests are writable");
  assert.ok(!code.includes("${{"), "no GitHub expression is interpolated into the script");
});

test("workflow: the triggers are exactly the specified events and types", () => {
  const on = TEMPLATE.match(/^on:\n((?: {2}.*\n)+)/m)[1];
  assert.equal(
    on,
    [
      "  pull_request:\n    types: [opened, edited, reopened]\n",
      "  issue_comment:\n    types: [created, edited]\n",
      "  pull_request_review_comment:\n    types: [created, edited]\n",
      "  pull_request_review:\n    types: [submitted, edited]\n",
      "  issues:\n    types: [opened, edited]\n",
    ].join(""),
  );
});

// ---- the script against a fake GitHub ----------------------------------------------------------------------------------------

const FOOTED = `The description.\n\n---\n\n${GEN}\n\n${SESSION}\n`;
const CLEAN = "The description.";

// Runs the real script from the template with a fake `github`, `context` and `core`; returns what it called.
async function run({ event, payload, bodies = {}, failWith }) {
  const calls = [];
  const logs = { notice: [], info: [], failed: [] };
  const method = (name, read) => async (args) => {
    calls.push([name, args]);
    if (!read && failWith) throw Object.assign(new Error(failWith.message || "boom"), { status: failWith.status });
    return { data: { body: bodies[name] } };
  };
  const rest = {
    pulls: {
      get: method("pulls.get", true), update: method("pulls.update"),
      getReviewComment: method("pulls.getReviewComment", true), updateReviewComment: method("pulls.updateReviewComment"),
      getReview: method("pulls.getReview", true), updateReview: method("pulls.updateReview"),
    },
    issues: { get: method("issues.get", true), update: method("issues.update"), getComment: method("issues.getComment", true), updateComment: method("issues.updateComment") },
  };
  const core = { notice: (m) => logs.notice.push(m), info: (m) => logs.info.push(m), setFailed: (m) => logs.failed.push(m) };
  const context = { eventName: event, payload, repo: { owner: "octo", repo: "demo" } };
  await new AsyncFunction("github", "context", "core", workflowScript())({ rest }, context, core);
  return { calls, logs, writes: calls.filter(([n]) => /update/i.test(n)) };
}
const sameRepoPr = { number: 7, head: { repo: { full_name: "octo/demo" } } };
const forkPr = { number: 7, head: { repo: { full_name: "someone/demo" } } };

test("script: PR description is read fresh and updated with pulls.update", async () => {
  const r = await run({ event: "pull_request", payload: { pull_request: sameRepoPr }, bodies: { "pulls.get": FOOTED } });
  assert.deepEqual(r.writes, [["pulls.update", { owner: "octo", repo: "demo", pull_number: 7, body: CLEAN }]]);
  assert.deepEqual(r.logs.failed, []);
});

test("script: issue description uses issues.update", async () => {
  const r = await run({ event: "issues", payload: { issue: { number: 3 } }, bodies: { "issues.get": FOOTED } });
  assert.deepEqual(r.writes, [["issues.update", { owner: "octo", repo: "demo", issue_number: 3, body: CLEAN }]]);
});

test("script: issue and PR comments use issues.updateComment", async () => {
  const r = await run({ event: "issue_comment", payload: { comment: { id: 55 }, issue: { number: 7 } }, bodies: { "issues.getComment": FOOTED } });
  assert.deepEqual(r.writes, [["issues.updateComment", { owner: "octo", repo: "demo", comment_id: 55, body: CLEAN }]]);
});

test("script: review comments use pulls.updateReviewComment", async () => {
  const r = await run({ event: "pull_request_review_comment", payload: { comment: { id: 66 }, pull_request: sameRepoPr }, bodies: { "pulls.getReviewComment": FOOTED } });
  assert.deepEqual(r.writes, [["pulls.updateReviewComment", { owner: "octo", repo: "demo", comment_id: 66, body: CLEAN }]]);
});

test("script: reviews use pulls.updateReview", async () => {
  const r = await run({ event: "pull_request_review", payload: { review: { id: 77 }, pull_request: sameRepoPr }, bodies: { "pulls.getReview": FOOTED } });
  assert.deepEqual(r.writes, [["pulls.updateReview", { owner: "octo", repo: "demo", pull_number: 7, review_id: 77, body: CLEAN }]]);
});

test("script: only edits when something changed (no footer, empty and null bodies)", async () => {
  for (const body of ["Plain.", "", null]) {
    const r = await run({ event: "pull_request", payload: { pull_request: sameRepoPr }, bodies: { "pulls.get": body } });
    assert.deepEqual(r.writes, [], `body ${JSON.stringify(body)}`);
    assert.deepEqual(r.logs.failed, []);
  }
});

test("script: uses the body as it is now, not the one in the event payload", async () => {
  const r = await run({ event: "pull_request", payload: { pull_request: { ...sameRepoPr, body: FOOTED } }, bodies: { "pulls.get": "Edited since, no footer." } });
  assert.deepEqual(r.writes, []);
});

test("script: fork PRs are skipped with a notice and exit 0, before any API call", async () => {
  for (const [event, payload] of [
    ["pull_request", { pull_request: forkPr }],
    ["pull_request_review", { review: { id: 1 }, pull_request: forkPr }],
    ["pull_request_review_comment", { comment: { id: 1 }, pull_request: forkPr }],
    ["pull_request", { pull_request: { number: 7, head: { repo: null } } }],
  ]) {
    const r = await run({ event, payload, bodies: {} });
    assert.deepEqual(r.calls, [], event);
    assert.equal(r.logs.notice.length, 1, event);
    assert.deepEqual(r.logs.failed, []);
  }
});

test("script: a 403 on the edit is a notice (read-only token), any other error fails the job", async () => {
  const ok = await run({ event: "pull_request", payload: { pull_request: sameRepoPr }, bodies: { "pulls.get": FOOTED }, failWith: { status: 403, message: "Resource not accessible by integration" } });
  assert.deepEqual(ok.logs.failed, []);
  assert.match(ok.logs.notice[0], /cannot edit/);
  await assert.rejects(run({ event: "pull_request", payload: { pull_request: sameRepoPr }, bodies: { "pulls.get": FOOTED }, failWith: { status: 500, message: "boom" } }), /boom/);
});

// ---- sync installs it --------------------------------------------------------------------------------------------------------

test("a new repo gets the workflow with the version filled in, and --check is clean", () => {
  const repo = fs.mkdtempSync(path.join(os.tmpdir(), "scrub-"));
  fs.writeFileSync(path.join(repo, "package.json"), JSON.stringify({ name: "demo-app", scripts: { test: "jest" } }));
  fs.writeFileSync(path.join(repo, "package-lock.json"), "{}");
  fs.writeFileSync(path.join(repo, "tsconfig.json"), "{}");
  const run1 = (args) => spawnSync(process.execPath, [path.join(ROOT, "scripts/sync.mjs"), "--repo", repo, ...args], { encoding: "utf8" });
  assert.equal(run1(["--init"]).status, 0);
  const written = fs.readFileSync(path.join(repo, DEST), "utf8");
  assert.equal(written, TEMPLATE.replace("{{conventions.version}}", fs.readFileSync(path.join(ROOT, "VERSION"), "utf8").trim()));
  assert.equal(run1(["--check"]).status, 0);
});
